#!/usr/bin/env python3
"""Who may build the node_modules of a base again, and what a build leaves, with npm faked:
python3 test_node_modules.py"""

import io
import json
import pathlib
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import daemon

PACKAGE = '{\n  "devDependencies": {"eslint": "8.57.0"}\n}\n'
# The caller, the body, and the answer or the refusal.
CASES = [
    ("master-x--seb", {"base": "19.0"}, "a bundle asks for the node_modules of its own base only"),
    ("master-x--seb", {"base": "nope"}, "base must be one of"),
    ("master-x--seb", {}, "held b1"),
    ("master-x--seb", {"reason": "eslint 9"}, "held b1"),
    (daemon.HOST, {}, "base must be one of"),
    (daemon.HOST, {"base": "master"}, "built master"),
]


def fake_npm(calls):
    def run(command, cwd=None, **kwargs):
        calls.append((command, (pathlib.Path(cwd) / "package-lock.json").read_text()))
        (pathlib.Path(cwd) / "node_modules" / ".bin").mkdir(parents=True)
        (pathlib.Path(cwd) / "node_modules" / "new").touch()
        (pathlib.Path(cwd) / "package-lock.json").write_text("new lock\n")
        return subprocess.CompletedProcess(command, 0)

    return run


def start_job(caller, verb, work):
    daemon.jobs["1"] = {"log": "", "result": work(io.StringIO()), "state": "done"}
    return 202, {"job": "1", **daemon.jobs["1"]["result"]}


def ask(caller, body):
    try:
        _code, answer = daemon.node_modules(caller, {}, body)
    except (ValueError, daemon.Refused) as error:
        return str(error)
    if "held" in answer:
        return f"held {answer['held']}"
    return f"built {answer['base']}"


def main():
    failures = []
    calls = []
    with tempfile.TemporaryDirectory() as name:
        root = pathlib.Path(name)
        base = root / "master"
        (base / "node_modules" / "old").mkdir(parents=True)
        (base / "package-lock.json").write_text("old lock\n")
        daemon.HELD_DIR = root / "held"
        daemon.HOST_BOX = "/box/host-box"
        daemon.get_worktree_base_folder = lambda name: str(root / name)
        daemon.read_package = lambda name: PACKAGE
        daemon.start_job = start_job
        daemon.subprocess.run = fake_npm(calls)
        for caller, body, expected in CASES:
            found = ask(caller, body)
            if not found.startswith(expected):
                failures.append(f"{caller} {body}: {found!r}, expected {expected!r}")
        fresh = str(base / ".node_modules.new")
        command = ["/box/host-box", "--net", "--dir", fresh, "--", "npm", "install", "--no-audit"]
        if calls != [([*command, "--no-fund"], "old lock\n")]:
            failures.append(f"npm: {calls}")
        found = (
            sorted(path.name for path in (base / "node_modules").iterdir()),
            sorted(path.name for path in (base / ".node_modules.old").iterdir()),
            (base / "package.json").read_text(),
            (base / "package-lock.json").read_text(),
            (base / ".node_modules.new").exists(),
        )
        expected = ([".bin", "new"], ["old"], PACKAGE, "new lock\n", False)
        if found != expected:
            failures.append(f"what a build leaves: {found}, expected {expected}")
        held = json.loads((daemon.HELD_DIR / "1.json").read_text())
        if held["reason"] != "eslint 9" or held["lines"][1:] != PACKAGE.splitlines():
            failures.append(f"b1 shows: {held['reason']!r} {held['lines']}")
        answer = daemon.HELD_DIR / "1.answer"
        answer.write_text(f"yes {held['digest']}\n")
        daemon.HELD.take(answer, daemon.send_held)
        found = json.loads((daemon.HELD_DIR / "1.result").read_text())["text"], len(calls)
        expected = "the node_modules of master is built again: a bundle loads it at its next start"
        expected = expected, 2
        if found != expected:
            failures.append(f"yes to b1: {found}, expected {expected}")
    for line in failures:
        print(line)
    cases = len(CASES) + 4
    print(f"{cases - len(failures)}/{cases} cases as expected")
    sys.exit(1 if failures else 0)


if __name__ == "__main__":
    main()
