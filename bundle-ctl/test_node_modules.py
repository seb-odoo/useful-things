#!/usr/bin/env python3
"""Who may build the node_modules of a package.json, and what a build leaves in the store, with
npm faked: python3 test_node_modules.py"""

import hashlib
import io
import json
import os
import pathlib
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import daemon

OLD = '{\n  "devDependencies": {"eslint": "8.57.0"}\n}\n'
PACKAGE = '{\n  "devDependencies": {"eslint": "10.12.0"}\n}\n'
KEY = hashlib.sha256(PACKAGE.encode()).hexdigest()[:16]
OLD_KEY = hashlib.sha256(OLD.encode()).hexdigest()[:16]
# The caller, the body, and the answer or the refusal, before the tree is built.
CASES = [
    ("master-x--seb", {"base": "19.0"}, "a bundle asks for the node_modules of its own base only"),
    ("master-x--seb", {"base": "nope"}, "base must be one of"),
    ("master-x--seb", {}, "held b1"),
    ("master-x--seb", {"reason": "eslint 10\x1b[1A"}, "held b1"),
    (daemon.HOST, {}, "base must be one of"),
]
BUILT = [
    ("master-x--seb", {}, f"tree {KEY}"),
    (daemon.HOST, {"base": "master"}, f"tree {KEY}"),
]
NEW = '{\n  "devDependencies": {"eslint": "10.13.0"}\n}\n'
# The git first in PATH, HOST_BOX, and whether the daemon serves.
BOXED_GIT = '#!/bin/sh\nexec "/box/host-box" -- /usr/bin/git "$@"\n'
GITS = [
    ("the git of host-ctl", BOXED_GIT, "/box/host-box", True),
    ("a git that runs no box", '#!/bin/sh\nexec /usr/bin/git "$@"\n', "/box/host-box", False),
    ("no HOST_BOX", BOXED_GIT, None, False),
]
# The head of odoo/master, its package.json, then the npm runs and whether its tree is there.
HEADS = [
    ("h1", PACKAGE, (0, True)),
    ("h2", NEW, (1, True)),
    ("h2", OLD, (0, False)),
]


def check_box(root, calls):
    """The daemon serves only when the git of its PATH runs HOST_BOX, and npm runs only in it."""
    failures = []
    folder = root / "bin"
    folder.mkdir()
    path = os.environ["PATH"]
    os.environ["PATH"] = f"{folder}:{path}"
    try:
        for name, text, box, serves in GITS:
            (folder / "git").write_text(text)
            (folder / "git").chmod(0o755)
            daemon.HOST_BOX = box
            try:
                daemon.check_box()
                served = True
            except (AttributeError, SystemExit):
                served = False
            if served != serves:
                failures.append(f"{name}: serves {served}, expected {serves}")
    finally:
        os.environ["PATH"] = path
    before = len(calls)
    daemon.HOST_BOX = None
    try:
        daemon.refresh_node_modules(io.StringIO(), "master", NEW.replace("13", "14"))
        found = "built"
    except daemon.Refused as error:
        found = str(error)
    if not found.startswith("no HOST_BOX") or len(calls) != before:
        failures.append(f"npm with no HOST_BOX: {found}, {calls[before:]}")
    return failures


def fake_npm(calls):
    def run(command, cwd=None, **kwargs):
        calls.append((command[:3], command[4:], (pathlib.Path(cwd) / "package-lock.json").exists()))
        (pathlib.Path(cwd) / "node_modules" / ".bin").mkdir(parents=True)
        (pathlib.Path(cwd) / "node_modules" / "new").touch()
        (pathlib.Path(cwd) / "package-lock.json").write_text("new lock\n")
        return subprocess.CompletedProcess(command, 0)

    return run


def start_job(caller, verb, work):
    daemon.jobs["1"] = {"log": "", "result": work(io.StringIO()), "state": "done"}
    return 202, {"job": "1", **daemon.jobs["1"]["result"]}


def ask(caller, body):
    try:
        _code, answer = daemon.node_modules(caller, {}, body)
    except (ValueError, daemon.Refused) as error:
        return str(error)
    if "held" in answer:
        return f"held {answer['held']}"
    return f"{'built' if 'job' in answer else 'tree'} {answer['tree']}"


def check_heads(root, calls):
    """What the timer of the daemon builds as the head of odoo/master moves, master's tree of
    PACKAGE being built already."""
    failures = []
    for head, package, expected in HEADS:
        daemon.read_base_heads = lambda repo, refs, head=head: {refs[0]: head}
        daemon.read_package = lambda name, package=package: package
        before = len(calls)
        daemon.build_node_modules()
        key = hashlib.sha256(package.encode()).hexdigest()[:16]
        found = len(calls) - before, (root / ".node_modules" / key / "node_modules").is_dir()
        if found != expected:
            failures.append(f"head {head}: {found}, expected {expected}")
    return failures


def main():
    failures = []
    calls = []
    with tempfile.TemporaryDirectory() as name:
        root = pathlib.Path(name)
        store = root / ".node_modules"
        (store / OLD_KEY).mkdir(parents=True)
        (store / OLD_KEY / "package.json").write_text(OLD)
        (root / "master-x--seb" / "odoo").mkdir(parents=True)
        link = f"/opt/node_modules/{OLD_KEY}/node_modules"
        (root / "master-x--seb" / "odoo" / "node_modules").symlink_to(link)
        daemon.HELD_DIR = root / "held"
        daemon.HOST_BOX = "/box/host-box"
        daemon.WORKTREE_CONTAINER = str(root)
        daemon.get_worktree_bundle_repo_folder = lambda bundle, repo: str(root / bundle / repo)
        daemon.read_package = lambda name: PACKAGE
        daemon.start_job = start_job
        daemon.subprocess.run = fake_npm(calls)
        for caller, body, expected in CASES:
            found = ask(caller, body)
            if not found.startswith(expected):
                failures.append(f"{caller} {body}: {found!r}, expected {expected!r}")
        held = json.loads((daemon.HELD_DIR / "1.json").read_text())
        found = held["reason"], [line for line in held["lines"] if line[0] in "+-"]
        expected = (
            "eslint 10\\x1b[1A",
            ['-  "devDependencies": {"eslint": "8.57.0"}', f"+{PACKAGE[2:-3]}"],
        )
        if found != expected:
            failures.append(f"b1 shows: {found}, expected {expected}")
        answer = daemon.HELD_DIR / "1.answer"
        answer.write_text(f"yes {held['digest']}\n")
        daemon.HELD.take(answer, daemon.send_held)
        found = json.loads((daemon.HELD_DIR / "1.result").read_text())["text"]
        expected = "the node_modules of master is built: the bundles on its package.json load it"
        if found != expected:
            failures.append(f"yes to b1: {found!r}, expected {expected!r}")
        for caller, body, expected in BUILT:
            found = ask(caller, body)
            if found != expected:
                failures.append(f"{caller} {body}, built: {found!r}, expected {expected!r}")
        command = ["/box/host-box", "--net", "--dir"], ["--", "npm", "install", "--no-audit"]
        if calls != [(command[0], [*command[1], "--no-fund"], False)]:
            failures.append(f"npm: {calls}")
        found = (
            sorted(path.name for path in store.iterdir()),
            sorted(path.name for path in (store / KEY).iterdir()),
            sorted(path.name for path in (store / KEY / "node_modules").iterdir()),
            (store / KEY / "package.json").read_text(),
            sorted(path.name for path in root.glob(".node_modules.*")),
        )
        expected = (
            sorted([KEY, OLD_KEY]),
            ["node_modules", "package-lock.json", "package.json"],
            [".bin", "new"],
            PACKAGE,
            [],
        )
        if found != expected:
            failures.append(f"what a build leaves: {found}, expected {expected}")
        failures += check_heads(root, calls)
        failures += check_box(root, calls)
    for line in failures:
        print(line)
    cases = len(CASES) + len(BUILT) + 4 + len(HEADS) + len(GITS) + 1
    print(f"{cases - len(failures)}/{cases} cases as expected")
    sys.exit(1 if failures else 0)


if __name__ == "__main__":
    main()
